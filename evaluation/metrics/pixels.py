"""Rhythm measured from pixels: an evaluation signal the agent never sees.

The agent's checks score animation curves, and its primitives are built to land on accents, so curve-based
accent recall partly measures what the planner was told to produce. This module instead measures the
*rendered* character: per-frame motion energy is the mean absolute difference between consecutive frames
(the camera is fixed, so only the character and its shadow change). Hits are found with the same
"fast motion, then a sharp stop" rule and compared with the dancer's accents.

Because it only needs frames, it also scores systems that have no curves at all (for example a video
generated by a diffusion model), which makes it the common yardstick across all systems.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from dancebuddy.tools.perception.beats import detect_hits, match, smooth

WIDTH = 160  # downscale before differencing: faster, and ignores noise at render resolution


def _gray_small(img: np.ndarray) -> np.ndarray:
    import cv2

    if img.ndim == 3 and img.shape[2] == 4:  # composite RGBA over white so transparency does not flicker
        alpha = img[:, :, 3:4].astype(float) / 255.0
        img = (img[:, :, :3].astype(float) * alpha + 255.0 * (1 - alpha)).astype(np.uint8)
    if img.ndim == 3:
        img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    h = max(1, int(round(img.shape[0] * WIDTH / img.shape[1])))
    return cv2.resize(img, (WIDTH, h), interpolation=cv2.INTER_AREA).astype(np.float32)


def motion_from_frames(frames: list[np.ndarray]) -> np.ndarray:
    """Per-frame motion energy (mean |difference| to the previous frame, 0-255 scale); frame 0 copies frame 1."""
    gray = [_gray_small(f) for f in frames]
    diffs = [float(np.mean(np.abs(b - a))) for a, b in zip(gray[:-1], gray[1:])]
    return np.array(diffs[:1] + diffs) if diffs else np.zeros(len(gray))


def motion_from_dir(frames_dir: str | Path, pattern: str = "frame_*.png") -> np.ndarray:
    import cv2

    paths = sorted(Path(frames_dir).glob(pattern))
    return motion_from_frames([cv2.imread(str(p), cv2.IMREAD_UNCHANGED) for p in paths])


def motion_from_video(video: str | Path, crop: tuple[int, int, int, int] | None = None) -> np.ndarray:
    """crop = (x, y, w, h) in pixels, to score only the character's part of a composited video."""
    import cv2

    cap = cv2.VideoCapture(str(video))
    frames = []
    while True:
        ok, f = cap.read()
        if not ok:
            break
        if crop:
            x, y, w, h = crop
            f = f[y:y + h, x:x + w]
        frames.append(f)
    cap.release()
    return motion_from_frames(frames)


def pixel_hits(motion: np.ndarray, fps: float, threshold: float = 0.25) -> list[int]:
    """Frames where the rendered character stops sharply after fast motion.

    A rendered character can stand perfectly still (motion exactly 0) for a while after a stop, which would
    put the local minimum at the end of the still stretch. Clamping at a small floor makes the hit land on the
    first still frame instead.
    """
    if len(motion) < 3 or motion.max() <= 1e-9:
        return []
    s = smooth(np.asarray(motion, float), 1.0)
    scale = max(float(np.percentile(s, 90)), 1e-6)
    s = np.maximum(s, 0.1 * scale)
    hits = detect_hits(s, fps, sigma=0, scale=scale)
    return [f for f, st in hits if st >= threshold]


def pixel_metrics(motion: np.ndarray, score: dict, tol_frames: int = 3) -> dict:
    """Accent recall / beat precision of the rendered character against the dancer, from pixels only."""
    n = min(len(motion), int(score["n_frames"]))
    hits = pixel_hits(motion[:n], float(score["fps"]))
    accents = [a for a in score["accents"] if a < n]
    beats = [b for b in score["beats"] if b < n]
    matched, _, offsets = match(accents, hits, tol_frames)
    on_beat, _, _ = match(hits, beats, tol_frames)
    return {
        "px_accent_recall": round(len(matched) / max(1, len(accents)), 3),
        "px_beat_precision": round(len(on_beat) / max(1, len(hits)), 3),
        "px_hits": len(hits),
        "px_frames": n,
    }
